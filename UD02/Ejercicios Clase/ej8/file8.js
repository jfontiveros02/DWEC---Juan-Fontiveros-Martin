let valor = Number(prompt("Escribe un número entre 1 y 5"));
if (valor >= 1 || valor <= 5) {
    switch (valor) {
        case 1:
            alert("One");
            break

        case 2:
            alert("Two");
            break

        case 3:
            alert("Three");
            break
        case 4:
            alert("Four");
            break
        case 5:
            alert("Five");
            break
        default:

            break
    }
}
